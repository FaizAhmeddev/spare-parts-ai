"""Regenerate docs/DATA_CONTRACT.md from the code-level schema (single source of truth)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from spareai.ingestion.schema import TABLES  # noqa: E402

lines = ["# Data contract", "",
         "Every data source (Excel, CSV, ERP/CMMS database) must deliver these logical tables.",
         "Column names are case/space-insensitive (`Part ID` -> `part_id`). Required columns",
         "must exist; optional columns may be missing and are filled with blanks. Formula",
         "columns (`stock_value_usd`, `total_cost_usd`, `downtime_cost_usd`) are recomputed.",
         "", "_Generated by `scripts/generate_data_contract.py` - do not edit by hand._", ""]
for spec in TABLES.values():
    lines += [f"## `{spec.name}`", "", spec.description, "",
              f"Primary key: `{', '.join(spec.primary_key)}`", ""]
    lines += ["| Column | Type | Required | Notes |", "|---|---|---|---|"]
    for c, t in spec.columns.items():
        note = []
        if c in spec.foreign_keys:
            note.append("-> `%s.%s`" % spec.foreign_keys[c])
        if c in spec.non_negative:
            note.append(">= 0")
        lines.append(f"| `{c}` | {t} | yes | {'; '.join(note)} |")
    for c, t in spec.optional.items():
        note = "-> `%s.%s`" % spec.foreign_keys[c] if c in spec.foreign_keys else ""
        lines.append(f"| `{c}` | {t} | no | {note} |")
    lines.append("")
(ROOT / "docs" / "DATA_CONTRACT.md").write_text("\n".join(lines), encoding="utf-8")
print("docs/DATA_CONTRACT.md written")
